def main():
    for code, ch_idx, title, body, question in ENRICHMENTS:
        path = CONTENT_DIR / f"module_{code}.json"
        if not path.exists():
            print(f"⚠️ 跳过 {code}：文件不存在")
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        chapter = data["chapters"][ch_idx]
        content = chapter["content"]

        # 幂等：已有补强标记则跳过
        if MARK in content:
            print(f"⏭️ {code} 第{ch_idx+1}章：已补强，跳过")
            continue

        # 在「## 案例复盘」前插入补强段落
        section = f"\n## {title}\n\n{body}\n\n{MARK}\n"
        if "## 案例复盘" in content:
            content = content.replace("## 案例复盘", section + "## 案例复盘", 1)
        else:
            content += "\n" + section
        chapter["content"] = content

        # 配套题目加入章节知识题
        if not any(q["stem"] == question["stem"] for q in chapter["questions"]):
            chapter["questions"].append(question)

        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        print(f"✅ {code} 第{ch_idx+1}章：已补强「{title}」+ 1 道题")


if __name__ == "__main__":
    main()
